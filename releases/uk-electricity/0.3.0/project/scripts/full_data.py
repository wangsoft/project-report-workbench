"""Extend the original data reader with source-located fuel, supply and history tables."""
import argparse
import json
import math
import re
from pathlib import Path
from openpyxl import load_workbook
from normalize import normalize, clean, REGIONS

FUELS={'coal':'Coal','oil':'Oil','gas':'Gas','nuclear':'Nuclear','hydro':'Hydro natural flow',
       'wind':'Wind','solar':'Solar','tidal':'Shoreline wave and tidal','bioenergy':'Bioenergy',
       'other':'Other fuels','pumped':'Pumped storage','battery':'Battery storage',
       'fossil':'Fossil fuels','renewables':'Renewables','total':'Total all generating companies'}
SUPPLY={'mpp':'Electricity generated by Major Power Producers (MPPs)',
        'other_generation':'Electricity generated by other generators','generation':'Total electricity generated',
        'own_other':'Own use by other generators','own_mpp':'Used in energy storage and other own use by MPPs',
        'to_england':'Electricity transferred to England (net of receipts)',
        'to_ni':'Electricity transferred to Northern Ireland (net of receipts)',
        'to_europe':'Electricity transferred to Europe (net of receipts)',
        'transmission':'Transmission losses','distribution':'Distribution losses and theft',
        'public_consumption':'Consumption from public supply [A]',
        'auto_consumption':'Consumption by autogenerators','consumption':'Total electricity consumed',
        'sales':'Electricity sales (public supply) [B]',
        'statistical_difference':'Statistical difference between calculated consumption [A] and sales [B]'}


def read_table(sheet, header_label: str, labels: dict, label_column: int, group=None) -> list:
    rows=list(sheet.iter_rows());header=next(r for r in rows if r[0].value==header_label)
    selected={}
    for key,label in labels.items():
        matches=[r for r in rows if clean(r[label_column].value)==label and (group is None or r[0].value==group)]
        if len(matches)!=1:raise ValueError(f'Missing/duplicate row {sheet.title}: {label}')
        selected[key]=matches[0]
    records=[]
    for c in header[label_column+1:]:
        if c.value is None:continue
        h=str(c.value).replace('2022 England6','2022 England')
        m=re.fullmatch(r'(\d{4}) (UK Total|England|Scotland|Wales|Northern Ireland)',h)
        if not m:raise ValueError('Unknown header '+h)
        values={};cells={}
        for key,row in selected.items():
            cell=row[c.column-1];value=cell.value
            # Historic unavailable values remain null, never zero-filled.
            if value is None or value=='[x]':value=None
            elif type(value) not in (float,int) or not math.isfinite(value):raise ValueError('Invalid cell '+cell.coordinate)
            values[key]=value;cells[key]=sheet.title+'!'+cell.coordinate
        records.append(dict(year=int(m[1]),region=m[2],values=values,locators=cells))
    return records


def full_normalize(path: str, year: int) -> dict:
    result=normalize(path,year);book=load_workbook(path,read_only=True,data_only=True)
    try:
        fuel=read_table(book['Electricity generation by fuel'],'Generator type',FUELS,1,'All generating companies')
        supply=read_table(book['Generation and supply'],'Components of electricity generation and supply',SUPPLY,0)
        result['fuel_detail']=[r for r in fuel if r['year']>=year-4]
        result['supply']=[r for r in supply if r['year']>=year-4]
        result['historical_records']=fuel
        for r in result['fuel_detail']+result['supply']:
            if any(v is None and k!='battery' for k,v in r['values'].items()):raise ValueError(f'Missing active-window value {r["year"]} {r["region"]}')
        return result
    finally:book.close()


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--data',required=True)
    p.add_argument('--year',required=True,type=int);p.add_argument('--out',required=True)
    a=p.parse_args();Path(a.out).write_text(json.dumps(full_normalize(a.data,a.year),ensure_ascii=False,indent=2))
